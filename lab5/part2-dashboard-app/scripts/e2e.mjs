import assert from 'node:assert/strict';
import { chromium } from 'playwright';
import postgres from 'postgres';

const base = process.env.TEST_BASE_URL || 'http://localhost:3002';
const { DEMO_EMAIL, DEMO_PASSWORD, POSTGRES_URL } = process.env;
assert(DEMO_EMAIL && DEMO_PASSWORD && POSTGRES_URL, 'Test credentials and database URL are required');
assert.equal(process.env.CI, 'true', 'Run this destructive test only against the disposable CI database');
const sql = postgres(POSTGRES_URL, { max: 1, prepare: false });
let browser;
let invoiceId;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage();
  page.setDefaultTimeout(20000);
  await page.goto(base + '/dashboard/invoices');
  await page.waitForURL(url => url.pathname === '/login');
  await page.getByLabel('Email').fill(DEMO_EMAIL);
  await page.getByLabel('Password').fill('incorrect-test-password');
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Unable to sign in' }).waitFor();
  await page.getByLabel('Email').fill(DEMO_EMAIL);
  await page.getByLabel('Password').fill(DEMO_PASSWORD);
  await page.getByRole('button', { name: 'Log in', exact: true }).click();
  await page.waitForURL(url => url.pathname === '/dashboard');
  await page.getByText('Revenue by month', { exact: true }).waitFor();
  console.log('PASS: invalid credentials, login, protected route and financial summary');
  await page.getByRole('link', { name: 'Customers', exact: true }).click();
  await page.getByRole('cell', { name: 'Alex Morgan', exact: true }).waitFor();
  await page.getByRole('link', { name: 'Invoices', exact: true }).click();
  await page.getByRole('link', { name: 'Next', exact: true }).click();
  await page.getByText('Page 2 of 2', { exact: true }).waitFor();
  await page.getByLabel('Search invoices').fill('no-such-customer');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByText('No invoices match your search.').waitFor();
  await page.getByRole('link', { name: 'Create invoice' }).click();
  await page.getByLabel('Customer', { exact: true }).selectOption({ label: 'Alex Morgan' });
  await page.getByLabel('Amount (USD)').fill('123.45');
  await page.getByRole('radio', { name: 'Pending' }).check();
  await page.getByRole('button', { name: 'Save invoice' }).click();
  await page.waitForURL(url => url.pathname === '/dashboard/invoices');
  const created = await sql`SELECT i.id,i.amount,i.status FROM invoices i JOIN customers c ON c.id=i.customer_id WHERE c.email='alex@example.test' AND i.amount=12345`;
  assert.equal(created.length, 1);
  invoiceId = created[0].id;
  assert.equal(created[0].status, 'pending');
  await page.getByLabel('Search invoices').fill('12345');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  const row = page.getByRole('row').filter({ hasText: '$123.45' });
  await row.getByRole('link', { name: 'Edit' }).click();
  await page.getByLabel('Amount (USD)').fill('234.56');
  await page.getByRole('radio', { name: 'Paid' }).check();
  await page.getByRole('button', { name: 'Save invoice' }).click();
  await page.waitForURL(url => url.pathname === '/dashboard/invoices');
  const [updated] = await sql`SELECT amount,status FROM invoices WHERE id=${invoiceId}`;
  assert.equal(updated.amount, 23456);
  assert.equal(updated.status, 'paid');
  await page.getByLabel('Search invoices').fill('23456');
  await page.getByRole('button', { name: 'Search', exact: true }).click();
  await page.getByRole('row').filter({ hasText: '$234.56' }).getByRole('button', { name: 'Delete invoice for Alex Morgan' }).click();
  await page.getByRole('row').filter({ hasText: '$234.56' }).waitFor({ state: 'detached' });
  assert.equal((await sql`SELECT id FROM invoices WHERE id=${invoiceId}`).length, 0);
  invoiceId = undefined;
  console.log('PASS: customers, search, pagination, create, update, delete and SQL verification');
  await page.getByRole('button', { name: 'Sign out' }).click();
  await page.waitForURL(url => url.pathname === '/');
  await page.goto(base + '/dashboard');
  await page.waitForURL(url => url.pathname === '/login');
  console.log('PASS: logout and access protection');
} finally {
  if (invoiceId) await sql`DELETE FROM invoices WHERE id=${invoiceId}`;
  await browser?.close();
  await sql.end();
}
